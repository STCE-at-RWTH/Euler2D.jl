function _pts_via_range_interp(xs, yrange, y_actual)
    interp = scale(interpolate(xs, BSpline(Linear())), yrange)
    x_actual = interp.(y_actual)
    return x_actual
end

function _pts_via_gridded_interp(xs, ys, y_actual)
    interp = interpolate((ys,), xs, Gridded(Linear()))
    x_actual = interp.(y_actual)
    return x_actual
end

dir_from_theta(θ) = SVector(sincos(θ)...) |> reverse

function vt_from_u_and_normal(u, e1_or_basis)
    return dimensionless_velocity(change_space_coordinates(u, e1_or_basis))[2]
end

function _vt_near_shock_from_theta(shock_pt, θ, Δξ, sim, tstep, bcs, gas)
    n = dir_from_theta(θ)
    Δpt = Δξ * n
    u_weno_appx = weno_approximate_u_at(shock_pt + Δpt, sim, tstep)
    return vt_from_u_and_normal(u_weno_appx, n)
end

function _vt_and_pushforward_near_shock_from_theta(shock_pt, θ, Δξ, sim, tstep, bcs, gas)
    n, dn = value_and_derivative(dir_from_theta, fdiff_backend, θ)
    Δpt = Δξ * n
    dΔpt = Δξ * dn
    # u_linear_appx = Euler2D.linear_approximate_u_at(shock_pt + Δpt, Δpt, sim, tstep, bcs, gas)
    (u_appx, (dudθ,)) = value_and_pushforward(weno_approximate_u_at, fdiff_backend, shock_pt + Δpt, (dΔpt,), Constant(sim), Constant(tstep))

    # dudθ = u_linear_appx.Dy * dΔpt
    # _marshalled = SVector(θ, u_linear_appx.y0...)
    _marshalled = SVector(θ, u_appx...)
    _marshalled_seed = SVector(one(θ), dudθ...)

    vt, dvt_dθ = value_and_pushforward(AutoForwardDiff(), _marshalled, (_marshalled_seed,)) do _θ_and_u
        _θ = _θ_and_u[1]
        _u = _θ_and_u[SVector(2, 3, 4, 5)]
        _e1 = dir_from_theta(_θ)
        @assert norm(_e1) ≈ 1.0
        return vt_from_u_and_normal(_u, _e1)
    end

    return vt, only(dvt_dθ)
end

function _vt_optim_f(θ, params)
    (_pt, _Δξ, _sim, _tstep, _bcs, _gas) = params
    vt_L = _vt_near_shock_from_theta(_pt, only(θ), -_Δξ, _sim, _tstep, _bcs, _gas)
    vt_R = _vt_near_shock_from_theta(_pt, only(θ), _Δξ, _sim, _tstep, _bcs, _gas)
    return (vt_L - vt_R)^2
end

function _vt_optim_f(out, θ, params)
    out[1] = _vt_optim_f(θ, params)
    return nothing
end

function _vt_optim_Df(out, θ, params)
    (_pt, _Δξ, _sim, _tstep, _bcs, _gas) = params
    vt_L, dvt_L_dθ = _vt_and_pushforward_near_shock_from_theta(_pt, only(θ), -_Δξ, _sim, _tstep, _bcs, _gas)
    vt_R, dvt_R_dθ = _vt_and_pushforward_near_shock_from_theta(_pt, only(θ), _Δξ, _sim, _tstep, _bcs, _gas)
    out[1] = 2 * (vt_L - vt_R) * (dvt_L_dθ - dvt_R_dθ)
    return nothing
end

function solve_for_shock_normal_at_point(pt, Δξ, sim, tstep, bcs, gas)
    optim_f = OptimizationFunction{true}(_vt_optim_f; grad = _vt_optim_Df)
    optim_problem = OptimizationProblem(optim_f, [0.0], (pt, Δξ, sim, tstep, bcs, gas); lb = [-π / 2], ub = [π / 2])
    return solve(optim_problem, Optim.BFGS())
end

"""
    ShockInterpolation

Represents specifically an interpolation of the points generated by the ``x``-axis symmetric bow shock problem.

Hüser was heckin' right.
"""
struct ShockInterpolation{T}
    points::Vector{SVector{2, T}}
    normals::Vector{SVector{2, T}}

    function ShockInterpolation{T}(points, normals) where {T}
        if length(points) != length(normals)
            throw(ArgumentError("There must be the same number of points and normal vectors."))
        end
        return new(points, normals)
    end
end

function ShockInterpolation(
        sim::CellBasedEulerSim{T, <:FVMCell{T}}, sensor_info, N_points;
        Cr = 1,
        bcs = (ExtrapolateToPhantom(), StrongWall(), ExtrapolateToPhantom(), ExtrapolateToPhantom(), StrongWall()),
        gas = DRY_AIR,
        skipN = 0,
        dropN = 0,
    ) where {T}
    all_shock_points = extract_bow_shock_points(sim, sensor_info)

    # speed penalty on a reinterpret here should be ok
    shock_points_r = reinterpret(reshape, Float64, all_shock_points)
    shock_ys = @view shock_points_r[2, :]
    shock_xs = @view shock_points_r[1, :]

    ymin = 0.0 # just in case we want to change this later?
    ymax = maximum(shock_ys)
    half_dy = (ymax - ymin) / (2 * N_points - 1)
    actual_ys = range(half_dy, ymax; length = N_points)
    actual_xs = if length(shock_ys) == length(cell_centers(sim, 2))
        # can use fast interpolation!
        _pts_via_range_interp(shock_xs, cell_centers(sim, 2), actual_ys)
    else
        #slow interpolation
        _pts_via_gridded_interp(shock_xs, shock_ys, actual_ys)
    end
    shock_points = map(SVector, @view(actual_xs[(begin + skipN):(end - dropN)]), @view(actual_ys[(begin + skipN):(end - dropN)]))
    # constant taken from Hüser
    dS = Cr * norm(minimum_cell_size(sim))^(1 / 2)
    optim_sols = map(shock_points) do pt
        solve_for_shock_normal_at_point(pt, dS, sim, 1, bcs, gas)
    end
    if !all(SciMLBase.successful_retcode, optim_sols)
        @warn "Finding the shock normals via a minimization procedure produced some failed optimization runs."
    end
    shock_normals = map(optim_sols) do sol
        dir_from_theta(only(sol.u))
    end
    return ShockInterpolation{T}(shock_points, shock_normals)
end

# prefer methods to direct field access in case I can re-use some of these other methods later?
x_knots(s::ShockInterpolation) = reinterpret(reshape, Float64, s.points)[1, :]
y_knots(s::ShockInterpolation) = reinterpret(reshape, Float64, s.points)[2, :]
function n_points(s::ShockInterpolation)
    return length(s.points)
end


