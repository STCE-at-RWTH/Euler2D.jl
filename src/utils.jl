function flip_velocity(u::ConservedProps{N, T, U1, U2, U3}, dim::Int) where {N, T, U1, U2, U3}
    scaling = SVector(ntuple(i -> i == dim ? -one(T) : one(T), N))
    return ConservedProps(u.ρ, scaling .* u.ρv, u.ρE)
