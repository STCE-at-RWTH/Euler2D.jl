## SIMPLE LINEAR APPROXIMATION

struct LinAppx{XT, YT, DYT}
    x0::XT
    y0::YT
    Dy::DYT
end

function _lin_appx_mul_impl(f_appx, x)
    return f_appx.y0 + f_appx.Dy * (x - f_appx.x0)
end

function _lin_appx_eachslice_impl(f_appx, x)
    return f_appx.y0 + mapreduce((Dy_k, dx_k) -> Dy_k * dx_k, +, eachslice(f_appx.Dy, dims = length(axes(f_appx.Dy))), (x - f_appx.x0))
end

function (f_appx::LinAppx)(x)
    return _lin_appx_mul_impl(f_appx, x)
end

function (f_appx::LinAppx{<:AbstractVector, YT, <:AbstractArray{<:Number, N}})(x) where {YT, N}
    if N == 2
        return _lin_appx_mul_impl(f_appx, x)
    else
        return _lin_appx_eachslice_impl(f_appx, x)
    end
end

### CHANGE COORDINATE VECTORS FOR VELOCITY SPACE

"""
    change_space_coordinates(u, V)
    change_space_coordinates(u, e_1)

Change the momentum vector of state ``u=[ρ, ρv..., ρE]`` into basis ``V``, or into the orthonormal basis
generated by choosing ``e_1`` as the first coordinate vector.

The columns of ``V`` are the basis vectors written in the standard Cartesian basis `I`. 
``e_1`` is the new "``x``"-axis written in the standard Cartesian basis `I`. 

See also [`translate_velocity_coordinates`](@ref), [`change_space_coordinates_and_shift_v`](@ref).
"""
function change_space_coordinates(u, V::Union{AbstractMatrix, UniformScaling})
    ρv_new = PlanePolygons.change_basis(select_middle(u), V)
    return vcat_state_components(u[begin], ρv_new, u[end])
end

function change_space_coordinates(u, e1::AbstractVector)
    B = PlanePolygons.orthonormal_basis(e1)
    return change_space_coordinates(u, B)
end

"""
    change_space_coordinates(u, e1_cur, e1_new)

Change the momentum vector of state `u` written in the basis defined by `e1_cur` to the basis defined by `e1_new`.
"""
function change_space_coordinates(u, e1_current::AbstractVector, e1_new::AbstractVector)
    B_cur = PlanePolygons.orthonormal_basis(e1_current)
    B_new = PlanePolygons.orthonormal_basis(e1_new)
    ρv_new = PlanePolygons.change_basis(select_middle(u), B_cur, B_new)
    return vcat_state_components(u[begin], ρv_new, u[end])
end

"""
    translate_velocity_coordinates(u_star, v0)

Shift the velocity coordinates to a frame moving at `v0`.
Total energy will change due to the new kinetic energy in the new frame.

See also [`change_space_coordinates`](@ref) or [`change_space_coordinates_and_shift_v`](@ref).
"""
function translate_velocity_coordinates(u_star, v0)
    ρ = first(u_star)
    v_star = dimensionless_velocity(u_star)
    v = v_star - v0
    ρe = dimensionless_internal_energy_density(u_star)
    ρv = ρ * v
    return vcat_state_components(ρ, ρv, ρe + ρv ⋅ v / 2)
end

"""
    change_space_coordinates_and_shift_v(u_star, T, v0)
    change_space_coordinates_and_shift_v(u_star, e1, v0)

Switch to a new coordinate space for velocity by switching to a frame moving at `v0` 
and then changing to the basis described by ``T`` or the orthonormal basis generated by 
choosing ``e_1`` as the first coordinate vector. 

See also [`change_space_coordinates`](@ref) or [`translate_velocity_coordinates`](@ref).
"""
function change_space_coordinates_and_shift_v(u_star, T_or_e1, v0)
    u1 = translate_velocity_coordinates(u_star, v0)
    return change_space_coordinates(u1, T_or_e1)
end

