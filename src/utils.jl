"""Get an appropriate `ε` for finite differences around `arg`."""
function fdiff_eps(arg::T) where {T <: Real}
    cbrt_eps = cbrt(eps(T))
    h = 2^(round(log2((1 + abs(arg)) * cbrt_eps)))
    return h
end

